def tool_description(p: Schema) -> str:
    """A primitive's description for the framework adapters: when to use it, then what the MCP server says."""
    own = p.get("description") or ""
    when = WHEN.get(p["tool"], "")
    return f"{when} {own}".strip()


def tool_schema(p: Schema) -> Schema:
    """A primitive's input as the MCP server lists it, with `required` always present (some frameworks need it)."""
    schema = dict(p["input"])
    schema.setdefault("required", [])
    return schema


