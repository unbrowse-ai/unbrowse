def served(api: Schema) -> List[Schema]:
    return list(api["primitives"])


def openclaw_file(api: Schema) -> str:
    """The OpenClaw manifest with its tool lists as the node serves them; everything else in it is the plugin's own."""
    plugin = json.loads(OPENCLAW.read_text(encoding="utf-8"))
    plugin.setdefault("contracts", {})["tools"] = [p["tool"] for p in served(api)]
    plugin["toolMetadata"] = {p["tool"]: ({"replaySafe": True} if p["method"] == "GET" else {"sideEffecting": True}) for p in served(api)}
    return json.dumps(plugin, indent=2, ensure_ascii=False) + "\n"


def hermes_yaml_file(api: Schema) -> str:
    text = HERMES_YAML.read_text(encoding="utf-8")
    listed = "provides_tools:\n" + "".join(f"  - {p['tool']}\n" for p in served(api))
    out, n = re.subn(r"(?m)^provides_tools:\n(?:  - .+\n|\n(?=  - ))*", lambda _m: listed, text)
    if n != 1:
        raise SystemExit(f"{HERMES_YAML.relative_to(ROOT)} has no provides_tools list to write")
    return out


def hermes_tools_file(api: Schema) -> str:
    text = HERMES_TOOLS.read_text(encoding="utf-8")
    listed = "TOOL_NAMES = (\n" + "".join(f'    "{p["tool"]}",\n' for p in served(api)) + ")\n"
    out, n = re.subn(r"(?m)^TOOL_NAMES = \((?:\n    \"[a-z_]+\",)*\n\)\n", lambda _m: listed, text)
    if n != 1:
        raise SystemExit(f"{HERMES_TOOLS.relative_to(ROOT)} has no TOOL_NAMES tuple to write")
    return out


def skill_copies() -> List[Tuple[Path, Callable[[Schema], str]]]:
    """The copies `integrations/sync-skills.py` makes of `skills/unbrowse`, as outputs of this generator."""
    import importlib.util

    spec = importlib.util.spec_from_file_location("sync_skills", ROOT / "integrations" / "sync-skills.py")
    sync = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sync)
    source = sync.SOURCE.read_text(encoding="utf-8")
    return [(path, lambda _api, m=meta, c=connect, d=drop: sync.copy_for(source, m, c, d)) for path, meta, connect, drop in sync.TARGETS]


