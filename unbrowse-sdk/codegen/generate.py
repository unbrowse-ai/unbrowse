def header(prefix: str, run: str, rest: str) -> List[str]:
    """The note each written file opens with, wrapped to the repository's width behind `prefix`."""
    text = (
        "Generated by unbrowse-sdk/codegen/generate.py from unbrowse-node/agent-api.json. Never edit it by hand: change "
        f"the node's registries, rewrite agent-api.json, then run {run}. {rest}"
    )
    return [(prefix + " " + line).rstrip() for line in textwrap.wrap(text, 118 - len(prefix) - 1, break_on_hyphens=False)]

Schema = Dict[str, Any]


def pascal(name: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[_\W]+", name) if w)


def camel(name: str) -> str:
    p = pascal(name)
    return p[:1].lower() + p[1:]


def short(tool: str) -> str:
    """A primitive's name without the tools' common prefix: `unbrowse_do` is `do`."""
    return tool[len("unbrowse_"):] if tool.startswith("unbrowse_") else tool


def ref_name(schema: Schema) -> Optional[str]:
    ref = schema.get("$ref")
    if ref is None:
        return None
    if not ref.startswith("#/types/"):
        raise SystemExit(f"a reference the generator can't follow: {ref}")
    return ref[len("#/types/"):]


def types_of(schema: Schema) -> List[str]:
    t = schema.get("type")
    if t is None:
        return []
    return list(t) if isinstance(t, list) else [t]


def discriminant(variant: Schema) -> Optional[str]:
    """The string a union's variant is told apart by: the first value of its first property that is a string enum."""
    for p in (variant.get("properties") or {}).values():
        values = p.get("enum") or []
        if values and isinstance(values[0], str):
            return values[0]
    return None


def variant_names(base: str, variants: List[Schema]) -> List[str]:
    """Names for a union's object variants: by what tells each apart when every one has it, else by position."""
    if len(variants) == 1:
        return [base]
    found = [discriminant(v) for v in variants]
    if all(found) and len(set(found)) == len(found):
        return [base + pascal(str(d)) for d in found]
    return [f"{base}{i + 1}" for i in range(len(variants))]


def is_object(schema: Schema) -> bool:
    return "object" in types_of(schema) and "properties" in schema


# ---------------------------------------------------------------- TypeScript

TS_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def ts_literal(v: Any) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    return json.dumps(v)


def ts_doc(text: str, pad: str) -> List[str]:
    return [f"{pad}/** {text} */"]


def ts_wrap(t: str) -> str:
    """A type as an array's element: a union or an intersection goes in brackets."""
    return f"({t})" if ("|" in t or "&" in t) and not t.startswith("{") else t


def ts_union(parts: List[str], indent: int) -> str:
    line = " | ".join(parts)
    if sum("\n" in p for p in parts) < 2 and len(line) <= 100:
        return line
    pad = " " * (indent + 2)
    return "".join(f"\n{pad}| {p}" for p in parts)


def ts_object(schema: Schema, indent: int) -> str:
    props: Optional[Schema] = schema.get("properties")
    extra = schema.get("additionalProperties")
    if not props:
        if isinstance(extra, dict):
            return f"Record<string, {ts_type(extra, indent)}>"
        # No fields and nothing else: an empty answer, or a command that takes no arguments.
        return "Record<string, never>" if props is not None else "Record<string, unknown>"
    required = set(schema.get("required") or [])
    fields = []
    for name, p in props.items():
        key = name if TS_IDENT.match(name) else json.dumps(name)
        opt = "" if name in required else "?"
        fields.append((p.get("description"), f"{key}{opt}: {ts_type(p, indent + 2)};"))
    flat = "{ " + " ".join(f for _, f in fields)[:-1] + " }"
    if all(d is None for d, _ in fields) and "\n" not in flat and len(flat) <= 100:
        return flat
    pad = " " * (indent + 2)
    lines = ["{"]
    for doc, f in fields:
        if doc:
            lines += ts_doc(doc, pad)
        lines.append(pad + f)
    lines.append(" " * indent + "}")
    return "\n".join(lines)


def ts_type(schema: Schema, indent: int = 0) -> str:
    name = ref_name(schema)
    if name:
        return name
    if "anyOf" in schema:
        return ts_union([ts_type(s, indent + 4) for s in schema["anyOf"]], indent)
    if "allOf" in schema:
        return " & ".join(ts_wrap(ts_type(s, indent)) for s in schema["allOf"])
    if "enum" in schema:
        return " | ".join(ts_literal(v) for v in schema["enum"])
    kinds = types_of(schema)
    if not kinds:
        return "unknown"
    out = []
    for k in kinds:
        if k == "string":
            out.append("string")
        elif k in ("integer", "number"):
            out.append("number")
        elif k == "boolean":
            out.append("boolean")
        elif k == "null":
            out.append("null")
        elif k == "array":
            items = schema.get("items")
            out.append(ts_wrap(ts_type(items, indent)) + "[]" if items else "unknown[]")
        elif k == "object":
            out.append(ts_object(schema, indent))
        else:
            raise SystemExit(f"a JSON type the generator doesn't know: {k}")
    return " | ".join(out)


def ts_params(command: Schema) -> Tuple[List[str], str]:
    """A command's method parameters, and the arguments object it sends.

    Its arguments go in order, the required ones first, each as a parameter by its name in camel case; one optional
    may be left out, which leaves it out of the arguments, and the node reads a missing argument as null. An input
    joined from parts (`allOf`) takes the object parts' arguments that way and the rest as one last parameter,
    spread into the arguments."""
    schema = command["input"]
    parts = schema["allOf"] if "allOf" in schema else [schema]
    params, sent = [], []
    rest = None
    for part in parts:
        if "properties" not in part:
            rest = part
            continue
        required = part.get("required") or []
        props = part["properties"]
        for name in [n for n in props if n in required] + [n for n in props if n not in required]:
            p = camel(name)
            opt = "" if name in required else "?"
            t = ts_type(props[name], 2)
            if "\n" in t:
                # A record of many fields reads better by the name of where it is spelled out.
                t = f'OwnerArgs<"{command["command"]}">["{name}"]'
            params.append(f"{p}{opt}: {t}")
            sent.append(name if p == name else f"{name}: {p}")
    if rest is not None:
        params.append(f"input: {ts_type(rest, 2)}")
        sent.append("...input")
    return params, "{ " + ", ".join(sent) + " }" if sent else ""


def ts_contract(api: Schema) -> List[str]:
    """The node's local contract and its errors, as constants."""
    local = api["local"]
    out = [
        "// ---- the node's contract ----",
        "",
        "/** The port a node listens on until its owner names another. */",
        f"export const DEFAULT_PORT = {local['default_port']};",
        "/** How long a client waits for one call: `do` may walk a page, and a call may heal by walking it again. */",
        f"export const CALL_WAIT_MS = {local['call_wait_secs'] * 1000};",
        "",
        "/** What a failed call means: its code (from the answer's status, or the code its body names), the status, the",
        " * class the SDK raises for it (none: a plain `UnbrowseError`) and what it says. Status 0 is the client's own. */",
        "export const ERRORS = [",
    ]
    for e in api["errors"]:
        out.append(f"  {{ code: {ts_literal(e['code'])}, status: {e['status']}, class: {ts_literal(e['class'])}, means: {ts_literal(e['means'])} }},")
    return out + ["] as const;", ""]


def ts_file(api: Schema) -> str:
    out: List[str] = header(
        "//",
        f"`{REGENERATE}` (`npm run gen`)",
        "The node's records as they cross the wire, in its own snake case, exactly as its schemas say; the agent "
        "primitives' requests; and the owner client's base, with one method per owner command. The hand-written "
        "client (client.ts, owner.ts) sits on top of it.",
    ) + [""] + ts_contract(api) + [
        "// ---- the node's records ----",
        "",
    ]
    for name in sorted(api["types"]):
        t = ts_type(api["types"][name])
        out.append(f"export type {name} ={'' if t.startswith(chr(10)) else ' '}{t};")
    out.append("")

    out += [
        "// ---- the agent API ----",
        "",
        "/** What each agent primitive takes and answers, by its tool's name. */",
        "export interface AgentPrimitives {",
    ]
    for p in api["primitives"]:
        out.append(f"  {p['tool']}: {{")
        out.append(f"    args: {ts_type(p['input'], 4)};")
        out.append(f"    result: {ts_type(p['returns'], 4)};")
        out.append("  };")
    out += [
        "}",
        'export type PrimitiveArgs<P extends keyof AgentPrimitives> = AgentPrimitives[P]["args"];',
        'export type PrimitiveResult<P extends keyof AgentPrimitives> = AgentPrimitives[P]["result"];',
        "",
        "/** A primitive's route: its method and path, the arguments it takes, and the names `unb` and the SDKs give it. */",
        "export type PrimitiveSpec = {",
        "  readonly tool: string;",
        '  readonly method: "GET" | "POST";',
        "  readonly path: string;",
        "  /** The arguments whose name over HTTP differs from the tool's. */",
        "  readonly renamed: readonly { readonly http: string; readonly tool: string }[];",
        "  readonly args: readonly string[];",
        "  readonly required: readonly string[];",
        "  readonly sdk: readonly string[];",
        "  readonly cli: string;",
        "};",
        "",
        "export const PRIMITIVES = {",
    ]
    keys = ("tool", "method", "path", "renamed", "args", "required", "sdk", "cli")
    for p in api["primitives"]:
        fields = ", ".join(f"{k}: {ts_json(p[k])}" for k in keys)
        out.append(f"  {p['tool']}: {{ {fields} }},")
    out += [
        "} as const satisfies Record<keyof AgentPrimitives, PrimitiveSpec>;",
        "",
        "/**",
        " * A primitive's request as its `/v1` route takes it: each argument by its HTTP name, a path's own in the path and",
        " * the rest in a GET's query or a POST's JSON body. An argument left out is left out of the request.",
        " */",
        "export function primitiveRequest<P extends keyof AgentPrimitives>(",
        "  tool: P,",
        "  args: PrimitiveArgs<P>,",
        '): { method: "GET" | "POST"; path: string; body?: Record<string, unknown> } {',
        "  const spec: PrimitiveSpec = PRIMITIVES[tool];",
        "  const given = args as Record<string, unknown>;",
        "  const http = (name: string) => spec.renamed.find((r) => r.tool === name)?.http ?? name;",
        "  const rest: [string, unknown][] = [];",
        "  let path = spec.path;",
        "  for (const name of spec.args) {",
        "    const slot = `{${http(name)}}`;",
        "    if (path.includes(slot)) path = path.replace(slot, encodeURIComponent(String(given[name])));",
        "    else if (given[name] !== undefined) rest.push([http(name), given[name]]);",
        "  }",
        '  if (spec.method === "POST") return { method: "POST", path, body: Object.fromEntries(rest) };',
        '  const query = rest.map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(String(v))}`).join("&");',
        '  return { method: "GET", path: query ? `${path}?${query}` : path };',
        "}",
        "",
        "// ---- the owner's commands ----",
        "",
        "/** What each owner command takes and answers, by the node's name for it. */",
        "export interface OwnerCommandTypes {",
    ]
    for c in api["owner"]:
        out.append(f"  {c['command']}: {{")
        out.append(f"    args: {ts_type(c['input'], 4)};")
        out.append(f"    result: {ts_type(c['returns'], 4)};")
        out.append("  };")
    out += [
        "}",
        'export type OwnerArgs<C extends keyof OwnerCommandTypes> = OwnerCommandTypes[C]["args"];',
        'export type OwnerResult<C extends keyof OwnerCommandTypes> = OwnerCommandTypes[C]["result"];',
        "",
        "/**",
        " * Every owner command as a typed method, each sending `POST /owner/{command}` through `command`. `UnbrowseOwner`",
        " * extends it, adding what a command alone can't say (the live events, a walk's picture) and a few friendlier",
        " * forms of these.",
        " */",
        "export abstract class OwnerCommands {",
        "  /** Any owner command by the node's name for it, with its arguments as the node takes them. */",
        "  protected abstract command<T = unknown>(cmd: string, args?: Record<string, unknown>, opts?: { signal?: AbortSignal }): Promise<T>;",
    ]
    for c in api["owner"]:
        params, sent = ts_params(c)
        result = ts_type(c["returns"], 2)
        out.append("")
        out += ts_doc(c["description"], "  ")
        out.append(f"  {c['sdk']['ts']}({', '.join(params)}): Promise<{result}> {{")
        call = f'this.command<OwnerResult<"{c["command"]}">>("{c["command"]}"' + (f", {sent})" if sent else ")")
        out.append(f"    return {call};")
        out.append("  }")
    out += ["}", ""]
    return "\n".join(out)


def ts_json(v: Any) -> str:
    """A value as a TypeScript literal: JSON with bare keys where they're names."""
    if isinstance(v, dict):
        if not v:
            return "{}"
        return "{ " + ", ".join(f"{k if TS_IDENT.match(k) else json.dumps(k)}: {ts_json(x)}" for k, x in v.items()) + " }"
    if isinstance(v, list):
        return "[" + ", ".join(ts_json(x) for x in v) + "]"
    return ts_literal(v)


# ---------------------------------------------------------------- Python


def py_lit(v: Any) -> str:
    """A value as a Python literal, its strings in double quotes as the package writes them."""
    if isinstance(v, dict):
        return "{" + ", ".join(f"{py_lit(k)}: {py_lit(x)}" for k, x in v.items()) + "}"
    if isinstance(v, list):
        return "[" + ", ".join(py_lit(x) for x in v) + "]"
    if isinstance(v, str):
        return json.dumps(v)
    return repr(v)


class Py:
    """The Python module being written: TypedDicts and aliases by name, each defined once."""

    def __init__(self, api: Schema):
        self.api = api
        self.classes: Dict[str, str] = {}
        self.aliases: Dict[str, Tuple[str, Set[str]]] = {}
        self.taken: Set[str] = set()

    def claim(self, name: str) -> str:
        if name in self.taken:
            raise SystemExit(f"two Python types would be named {name}: give one a name of its own in the node's schemas")
        self.taken.add(name)
        return name

    def resolve(self, schema: Schema) -> Schema:
        name = ref_name(schema)
        return self.api["types"][name] if name else schema

    def type(self, schema: Schema, hint: str, refs: Set[str]) -> str:
        """The annotation for `schema`; an object it holds becomes a TypedDict named `hint`."""
        name = ref_name(schema)
        if name:
            refs.add(name)
            return name
        if "anyOf" in schema:
            members = [s for s in schema["anyOf"] if types_of(s) != ["null"]]
            nullable = len(members) < len(schema["anyOf"])
            objects = [s for s in members if is_object(s)]
            names = iter(variant_names(hint, objects))
            parts = [self.type(s, next(names) if is_object(s) else hint, refs) for s in members]
            t = parts[0] if len(parts) == 1 else f"Union[{', '.join(parts)}]"
            return f"Optional[{t}]" if nullable else t
        if "allOf" in schema:
            return self.joined(schema["allOf"], hint, refs)
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            t = "Literal[" + ", ".join(py_lit(v) for v in values) + "]"
            return f"Optional[{t}]" if None in schema["enum"] else t
        kinds = [k for k in types_of(schema) if k != "null"]
        nullable = "null" in types_of(schema)
        if not kinds:
            return "None" if nullable else "Any"
        parts = []
        for k in kinds:
            if k == "string":
                parts.append("str")
            elif k == "integer":
                parts.append("int")
            elif k == "number":
                parts.append("float")
            elif k == "boolean":
                parts.append("bool")
            elif k == "array":
                items = schema.get("items")
                parts.append(f"List[{self.type(items, hint + 'Item', refs)}]" if items else "List[Any]")
            elif k == "object":
                parts.append(self.object(schema, hint, refs))
        t = parts[0] if len(parts) == 1 else f"Union[{', '.join(parts)}]"
        return f"Optional[{t}]" if nullable else t

    def object(self, schema: Schema, hint: str, refs: Set[str], doc: Optional[str] = None) -> str:
        props = schema.get("properties")
        extra = schema.get("additionalProperties")
        if not props:
            if isinstance(extra, dict):
                return f"Dict[str, {self.type(extra, hint + 'Value', refs)}]"
            return "Dict[str, Any]"
        refs.add(hint)
        self.typeddict(hint, props, set(schema.get("required") or []), doc)
        return hint

    def joined(self, parts: List[Schema], hint: str, refs: Set[str]) -> str:
        """An `allOf`: its object parts as one TypedDict. A union among the parts can't join a TypedDict, so its
        fields are named in the docstring and left out of the type."""
        props: Schema = {}
        required: Set[str] = set()
        unions = []
        for part in parts:
            whole = self.resolve(part)
            if is_object(whole):
                props.update(whole["properties"])
                required.update(whole.get("required") or [])
            else:
                unions.append(ref_name(part) or "a union")
                self.type(part, hint + "Part", set())
        doc = f"Also one of {', '.join(unions)}'s shapes, whose fields it carries beside these." if unions else None
        refs.add(hint)
        self.typeddict(hint, props, required, doc)
        return hint

    def typeddict(self, name: str, props: Schema, required: Set[str], doc: Optional[str]) -> None:
        self.claim(name)
        fields = []
        for key, p in props.items():
            refs: Set[str] = set()
            fields.append((key, self.type(p, name + pascal(key), refs), key in required, p.get("description")))
        must = [f for f in fields if f[2]]
        may = [f for f in fields if not f[2]]
        plain = all(k.isidentifier() and not keyword.iskeyword(k) for k, *_ in fields)
        lines: List[str] = []
        if not plain:
            # A field Python can't name in a class body: the functional form, its types in quotes.
            body = lambda fs: "{" + ", ".join(f"{k!r}: {t!r}" for k, t, *_ in fs) + "}"
            if must and may:
                lines.append(f"_{name}Required = TypedDict({('_' + name + 'Required')!r}, {body(must)})")
                lines.append(f"{name} = TypedDict({name!r}, {body(may)}, total=False)  # and _{name}Required's")
            else:
                lines.append(f"{name} = TypedDict({name!r}, {body(fields)}" + (")" if must else ", total=False)"))
            self.classes[name] = "\n".join(lines)
            return

        def block(cls: str, bases: str, fs: List[Tuple[str, str, bool, Optional[str]]], text: Optional[str]) -> List[str]:
            b = [f"class {cls}({bases}):"]
            if text:
                b.append(f'    """{text}"""')
                b.append("")
            for k, t, _, d in fs:
                b.append(f"    {k}: {t}")
                if d:
                    b.append(f'    """{d}"""')
            if not fs and not text:
                b.append("    pass")
            return b

        if must and may:
            lines += block(f"_{name}Required", "TypedDict", must, None)
            lines += ["", ""]
            lines += block(name, f"_{name}Required, total=False", may, doc)
        elif must:
            lines += block(name, "TypedDict", must, doc)
        else:
            lines += block(name, "TypedDict, total=False", may, doc)
        self.classes[name] = "\n".join(lines)

    def named(self, name: str, schema: Schema) -> None:
        """A type of the manifest's own, under its name."""
        if is_object(schema):
            self.object(schema, name, set())
            return
        if "allOf" in schema:
            self.joined(schema["allOf"], name, set())
            return
        refs: Set[str] = set()
        expr = self.type(schema, name, refs)
        self.claim(name)
        self.aliases[name] = (expr, refs - {name})


def py_params(c: Schema, py: Py) -> Tuple[List[str], str]:
    """A command's method parameters, in the TypeScript method's order, and the arguments object it sends. An optional
    argument left as None is left out, which the node reads as null."""
    schema = c["input"]
    parts = schema["allOf"] if "allOf" in schema else [schema]
    params, must, may = [], [], []
    rest = None
    for part in parts:
        if "properties" not in part:
            rest = part
            continue
        required = part.get("required") or []
        props = part["properties"]
        for name in [n for n in props if n in required] + [n for n in props if n not in required]:
            p = name + "_" if keyword.iskeyword(name) else name
            hint = pascal(c["command"]) + pascal(name)
            t = py.type(props[name], hint, set())
            if name in required:
                params.append(f"{p}: {t}")
                must.append(f"{py_lit(name)}: {p}")
            else:
                params.append(f"{p}: {t if t.startswith('Optional[') else f'Optional[{t}]'} = None")
                may.append(f"{name}={p}")
    if rest is not None:
        params.append(f"input: {py.type(rest, pascal(c['command']) + 'Input', set())}")
        must.append("**input")
    args = "{" + ", ".join(must) + "}"
    if may:
        return params, f"_args({args}, {', '.join(may)})"
    return params, args if must else ""


def py_file(api: Schema) -> str:
    py = Py(api)
    for name in sorted(api["types"]):
        py.named(name, api["types"][name])
    for p in api["primitives"]:
        base = pascal(short(p["tool"]))
        py.object(p["input"], base + "Args", set())
        if not ref_name(p["returns"]):
            py.type(p["returns"], base + "Result", set())
    methods: List[str] = []
    for c in api["owner"]:
        params, sent = py_params(c, py)
        result = py.type(c["returns"], pascal(c["command"]) + "Result", set())
        call = f'self.command("{c["command"]}"' + (f", {sent})" if sent else ")")
        methods += [
            "",
            f"    def {c['sdk']['py']}({', '.join(['self'] + params)}) -> {result}:",
            f'        """{c["description"]}"""',
            f"        return {call}",
        ]

    doc = header(
        "#",
        f"``{REGENERATE}``",
        "The node's records as they cross the wire, in its own snake case, as TypedDicts (plain dicts when the program "
        "runs); the agent primitives' requests; and ``OwnerCommands``, the owner client's base, with one method per "
        "owner command. The hand-written client (client.py, models.py, owner.py) sits on top of it.",
    )
    out: List[str] = [
        '"""' + doc[0][2:],
        *[line[2:] for line in doc[1:-1]],
        doc[-1][2:] + '"""',
        "",
        "from __future__ import annotations",
        "",
        "import urllib.parse",
        "from typing import Any, Dict, List, Literal, Mapping, Optional, Tuple, TypedDict, Union",
        "",
        "",
        "# ---- the node's contract ----",
        "",
        "#: The port a node listens on until its owner names another.",
        f"DEFAULT_PORT = {api['local']['default_port']}",
        "#: How long a client waits for one call, in seconds: ``do`` may walk a page, and a call may heal by walking it again.",
        f"CALL_WAIT_SECS = {api['local']['call_wait_secs']}",
        "",
        "#: What a failed call means: (code, status, the class the SDK raises, or '' for a plain ``UnbrowseError``, what it",
        "#: says). The code comes from the answer's status, or the code its body names; status 0 is the client's own.",
        "ERRORS: Tuple[Tuple[str, int, str, str], ...] = (",
        *[f"    ({py_lit(e['code'])}, {e['status']}, {py_lit(e['class'])}, {py_lit(e['means'])})," for e in api["errors"]],
        ")",
        "",
        "",
        "# ---- the node's records ----",
    ]
    for name in sorted(py.classes):
        out += ["", "", py.classes[name]]
    # An alias is a value when the module loads: each comes after the aliases it names (the classes are all above).
    done: Set[str] = set()

    def alias(name: str) -> None:
        if name in done or name not in py.aliases:
            return
        done.add(name)
        expr, refs = py.aliases[name]
        for r in sorted(refs):
            alias(r)
        out.extend(["", "", f"{name} = {expr}"])

    for name in sorted(py.aliases):
        alias(name)

    out += [
        "",
        "",
        "# ---- the agent API ----",
        "",
        "# Each primitive's route: its method and path, the arguments it takes, and the names `unb` and the SDKs give it.",
        "PRIMITIVES: Dict[str, Dict[str, Any]] = {",
    ]
    keys = ("tool", "method", "path", "renamed", "args", "required", "sdk", "cli")
    for p in api["primitives"]:
        out.append(f"    {py_lit(p['tool'])}: {py_lit({k: p[k] for k in keys})},")
    out += [
        "}",
        "",
        "",
        "def primitive_request(tool: str, args: Mapping[str, Any]) -> Tuple[str, str, Optional[Dict[str, Any]]]:",
        '    """A primitive\'s request as its ``/v1`` route takes it: the method, the path and the JSON body (None for a GET).',
        "",
        "    Each argument goes by its HTTP name, a path's own in the path and the rest in a GET's query or a POST's body. An",
        '    argument left out, or None, is left out of the request."""',
        "    spec = PRIMITIVES[tool]",
        '    http = {r["tool"]: r["http"] for r in spec["renamed"]}',
        '    path = spec["path"]',
        "    rest: Dict[str, Any] = {}",
        '    for name in spec["args"]:',
        '        slot = "{" + http.get(name, name) + "}"',
        "        if slot in path:",
        "            path = path.replace(slot, urllib.parse.quote(str(args[name]), safe=\"\"))",
        "        elif args.get(name) is not None:",
        "            rest[http.get(name, name)] = args[name]",
        '    if spec["method"] == "POST":',
        '        return "POST", path, rest',
        '    query = urllib.parse.urlencode(rest, quote_via=urllib.parse.quote)',
        '    return "GET", f"{path}?{query}" if query else path, None',
        "",
        "",
        "# ---- the owner's commands ----",
        "",
        "",
        "def _args(given: Dict[str, Any], **optional: Any) -> Dict[str, Any]:",
        "    # An optional argument left as None isn't sent: the node reads a missing argument as null.",
        "    return {**given, **{k: v for k, v in optional.items() if v is not None}}",
        "",
        "",
        "class OwnerCommands:",
        '    """Every owner command as a typed method, each sending ``POST /owner/{command}`` through ``command``.',
        "",
        "    ``UnbrowseOwner`` extends it with what a command alone can't say (the live events, a walk's picture).\"\"\"",
        "",
        "    def command(self, name: str, args: Optional[Dict[str, Any]] = None) -> Any:",
        '        """Any owner command by the node\'s name for it, with its arguments as the node takes them."""',
        "        raise NotImplementedError",
    ]
    out += methods
    out.append("")
    return "\n".join(out)


