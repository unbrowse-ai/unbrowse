#!/usr/bin/env python3
"""Writes the SDKs' typed layers from the node's API, `unbrowse-node/agent-api.json`.

The node writes that file from its own registries (`PRIMITIVES`, `OWNER_COMMANDS`, the types in `apischema.rs`), so
what is written here can't drift from what the node runs:

- `unbrowse-sdk/typescript/src/generated.ts`: the wire types, the agent primitives' requests, and `OwnerCommands`,
  the owner client's base with one method per command;
- `unbrowse-sdk/python/src/unbrowse/_generated.py`: the same for Python;
- `unbrowse-sdk/typescript/src/adapters/tools.ts` and `unbrowse-sdk/python/src/unbrowse/adapters/_tools.py`: each agent
  primitive as a framework tool (LangChain, the Vercel AI SDK, Mastra, OpenAI Agents), with the MCP server's name,
  description and input schema, so the framework adapters offer exactly the tools the MCP server lists;
- the agent plugins' lists of the node's tools: `integrations/openclaw/openclaw.plugin.json` (`contracts.tools`, and
  `toolMetadata`: a primitive served by GET is replay-safe, any other side-effecting), and the Hermes plugin's
  `provides_tools` (`plugin.yaml`) and `TOOL_NAMES` (`tools.py`). Only those parts of the files are written;
- the copies of `skills/unbrowse` the plugins carry (`integrations/sync-skills.py` says how each is made).

The hand-written clients sit on top. Run it after the manifest changes; `--check` writes nothing and fails, naming
each file, when one is stale (CI runs it). Python 3.9+, the standard library only, and the same output every run.
"""

