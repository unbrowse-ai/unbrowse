def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; fail, naming each file, when one is stale")
    ap.add_argument("--spec", type=Path, default=SPEC, help="the manifest to read (default: unbrowse-node/agent-api.json)")
    opts = ap.parse_args()
    api = json.loads(opts.spec.read_text(encoding="utf-8"))
    if api.get("version") != 2:
        raise SystemExit(f"agent-api.json is version {api.get('version')}; this generator reads version 2")
    stale = []
    for path, make in OUTPUTS:
        text = make(api)
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        if opts.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("stale, not as agent-api.json says:", file=sys.stderr)
        for s in stale:
            print(f"  {s}", file=sys.stderr)
        print(f"run `{REGENERATE}` and commit what it writes", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
