// Luminary for AC3: prove the producer→consumer EDGE forms in the LIVE buildSkillOperationGraph when
// one op yields a localStorage token and another requires it — NO hand-built bindings (the Step-8
// over-claim, now a met claim). Run: bun bench/capability/test_localstorage_dag_edge.ts
import { buildSkillOperationGraph } from "../../src/lib/graph-core/index.ts";

let fails = 0;
function ok(c: boolean, m: string) { if (!c) { console.error("  FAIL", m); fails++; } else console.log("  ok  ", m); }

// Two real endpoints: a producer (login) and a consumer whose query references `sessionId`.
const endpoints: any = [
  { endpoint_id: "login", url_template: "https://x.example/login", method: "POST", semantic: {} },
  { endpoint_id: "feed", url_template: "https://x.example/feed", method: "GET", query: { sessionId: "{sessionId}" }, semantic: {} },
];

// pageState carries the captured localStorage — the live builder promotes it to YIELDS bindings.
const graph: any = buildSkillOperationGraph(endpoints, { localStorage: { sessionId: "anti-bot-token-xyz" } });

// 1. the producer op carries a first-class localStorage YIELDS binding (auto-generated by the builder)
const login = graph.operations.find((o: any) => o.endpoint_id === "login");
ok(!!login.provides.find((p: any) => p.key === "sessionId" && p.type === "localStorage"),
   "builder auto-generated a localStorage yields binding on op.provides (no hand-built binding)");

// 2. the consumer op auto-required sessionId from its query (existing inferRequires)
const feed = graph.operations.find((o: any) => o.endpoint_id === "feed");
ok(!!feed.requires.find((r: any) => r.key === "sessionId"),
   "consumer auto-required sessionId from its query param");

// 3. THE AC3 PROOF: the EXACT producer→consumer edge (login → feed, binding_key sessionId).
const edge = (graph.edges ?? []).find((e: any) =>
  e.from_operation_id === "login" && e.to_operation_id === "feed" && e.binding_key === "sessionId");
if (!edge) console.error("  edges dump:", JSON.stringify(graph.edges));
ok(!!edge, "AC3: the EXACT login→feed edge on sessionId appears in the LIVE graph (no hand-built bindings)");

// 4. additive: an unrelated key gets no spurious localStorage yields
ok(!login.provides.find((p: any) => p.key === "unrelated"), "no spurious yields for keys not in localStorage");

console.log(fails === 0 ? "\nAC3 DAG-EDGE WITNESS PASSES" : `\n${fails} FAILED`);
process.exit(fails === 0 ? 0 : 1);
